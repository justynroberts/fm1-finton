def harmony():
    out = ["/* generated by tools/gen_assets.py: Rollwerk's chord vocabulary and progression library */",
           "#pragma once", "#include <stdint.h>", "",
           "/* qualities: intervals (4th = 0xFF for a triad) and the name suffix */",
           "enum { " + ", ".join("Q_" + q.upper() for q in QUAL) + ", NQUAL };",
           "static const uint8_t Q_IV[NQUAL][4] = {{0, 3, 7, 255}, {0, 4, 7, 255}, {0, 3, 7, 10}, {0, 4, 7, 11}, {0, 2, 7, 255}, {0, 5, 7, 255}, {0, 3, 6, 255}};",
           'static const char *const Q_SUFFIX[NQUAL] = {"m", "", "m7", "maj7", "sus2", "sus4", "dim"};',
           "/* the colour tone: the 4th of a 7th chord, else this above the root */",
           "static const uint8_t Q_COLOUR[NQUAL] = {10, 2, 10, 11, 10, 2, 9};",
           "typedef struct { const char *id; uint8_t offset, q, colour; } vocab_t;"]
    for mode, v in VOCAB.items():
        rows = ", ".join('{"%s", %d, Q_%s, %d}' % (i.replace("\x7f", "o"), o, q.upper(), 1 if k >= 7 else 0) for k, (i, o, q) in enumerate(v))
        out.append(f"static const vocab_t VOCAB_{mode.upper()}[{len(v)}] = {{{rows}}};")
    out.append(f"#define NVOCAB_MINOR {len(VOCAB['minor'])}\n#define NVOCAB_MAJOR {len(VOCAB['major'])}")
    names = list(MOODS)
    out.append('#define NMOOD %d' % len(names))
    out.append('static const char *const MOOD_NAME[NMOOD] = {%s};' % ", ".join('"%s"' % n.upper() for n in names))
    allp, start = [], []
    for n in names:
        start.append(len(allp))
        mode = "major" if n == "major" else "minor"
        ids = [i for i, _, _ in VOCAB[mode]]
        for prog in MOODS[n]:
            bars = []
            for tok in prog.split():
                d, _, h = tok.partition("/")
                bars.append((ids.index(d), ids.index(h) if h else 255))
            assert len(bars) == 8, prog
            allp.append(bars)
    start.append(len(allp))
    out.append("static const uint8_t MOOD_START[NMOOD + 1] = {%s};" % ", ".join(map(str, start)))
    out.append("#define NPROG %d" % len(allp))
    out.append("static const uint8_t PROG[NPROG][8][2] = {")
    for b in allp:
        out.append("    {" + ", ".join("{%d, %d}" % x for x in b) + "},")
    out.append("};")
    (GEN / "finton_harmony.h").write_text("\n".join(out) + "\n")



