"""Generate Finton's constant data: firmware/gen/apex_font.h, finton_logo.h and apex_tables.h.

  python3 tools/gen_assets.py

The chip has no FPU, so every curve the engine needs is computed here once and
written into the source as integers.

Type: M PLUS 1 Code (SIL OFL 1.1, assets/fonts) in three cuts on the 6x12, 8x16 and 14x28
cells the layouts were drawn on, and its katakana mirrored for the rain. The logo: assets/logo.png.
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "firmware" / "gen"
FS = 44100
BG = (0, 6, 2)                   # the ground, render.c K_BG: black with the faintest green
CR = 32                      # frames per control tick (engine.c)


FONT = "MPLUS1Code.ttf"           # M PLUS 1 Code (SIL OFL 1.1): one family for the type and the rain


def font(name, size, weight, cw, ch, base):
    """M PLUS 1 Code at a cell of cw x ch pixels, 4-bit alpha, two pixels a byte (high nibble left)"""
    from PIL import Image, ImageDraw, ImageFont
    f = ImageFont.truetype(str(ROOT / "assets" / "fonts" / FONT), size)
    f.set_variation_by_axes([weight])
    bpr = (cw + 1) // 2
    data = []
    for c in range(32, 127):
        im = Image.new("L", (cw, ch), 0)
        ImageDraw.Draw(im).text((cw / 2, base), chr(c), font=f, fill=255, anchor="ms")
        data += pack(im, cw, ch)
    body = ", ".join(str(b) for b in data)
    return (f"static const uint8_t {name}_DATA[{len(data)}] = {{{body}}};\n"
            f"static const apex_font_t {name} = {{{cw}, {ch}, {bpr}, {name}_DATA}};\n")


def pack(im, cw, ch):
    px = im.load()
    out = []
    for y in range(ch):
        row = [min(15, (px[x, y] + 8) // 17) for x in range(cw)] + [0]
        out += [row[x] << 4 | row[x + 1] for x in range(0, cw, 2)]
    return out


# the rain: katakana and numerals, mirrored as the film's code is, squeezed into 8 x 12
RAIN = "アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン" + "0123456789" + ":=*+<>"


def rain():
    from PIL import Image, ImageDraw, ImageFont, ImageOps
    f = ImageFont.truetype(str(ROOT / "assets" / "fonts" / FONT), 40)
    f.set_variation_by_axes([500])
    data = []
    for c in RAIN:
        big = Image.new("L", (48, 48), 0)
        ImageDraw.Draw(big).text((24, 24), c, font=f, fill=255, anchor="mm")
        big = big.crop(big.getbbox() or (0, 0, 48, 48))
        small = Image.new("L", (8, 12), 0)
        g = ImageOps.mirror(big).resize((7, 10), Image.LANCZOS)
        small.paste(g, (0, 1))
        data += pack(small, 8, 12)
    body = ", ".join(str(b) for b in data)
    return (f"#define NRAIN {len(RAIN)}\n"
            f"static const uint8_t RAIN_DATA[{len(data)}] = {{{body}}};\n"
            f"static const apex_font_t F_RAIN = {{8, 12, 4, RAIN_DATA}};   /* glyph i at RAIN_DATA + i * 48 */\n")


def fonts():
    out = ["/* generated by tools/gen_assets.py from M PLUS 1 Code (SIL OFL 1.1, assets/fonts) */",
           "#pragma once", "#include <stdint.h>",
           "typedef struct { uint8_t w, h, bpr; const uint8_t *data; } apex_font_t;   /* ASCII 32..126, 4-bit alpha */", ""]
    out.append(font("F12", 10.6, 500, 6, 12, 10))
    out.append(font("F16", 14.0, 640, 8, 16, 13))
    out.append(font("F28", 24.0, 680, 14, 28, 23))
    out.append(rain())
    (GEN / "apex_font.h").write_text("\n".join(out))


def logo():
    """the dog, RGB565 on the screen's ground, at 112 and 20 px"""
    from PIL import Image
    src = Image.open(ROOT / "assets" / "logo.png").convert("RGBA")
    src = src.crop(src.getbbox())
    out = ["/* generated by tools/gen_assets.py from assets/logo.png */", "#pragma once", "#include <stdint.h>", ""]
    for name, size in (("LOGO_L", 112), ("LOGO_S", 22)):
        w = size
        h = round(size * src.height / src.width)
        im = Image.new("RGBA", (w, h), BG + (255,))
        im.alpha_composite(src.resize((w, h), Image.LANCZOS))
        vals = []
        for r, g, b, _ in im.convert('RGBA').getdata():
            vals.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
        out.append(f"#define {name}_W {w}\n#define {name}_H {h}")
        out.append(arr("uint16_t", name, vals, 16))
    (GEN / "finton_logo.h").write_text("\n".join(out))


def arr(ctype, name, vals, per=12):
    lines = [", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def tables():
    out = ["/* generated by tools/gen_assets.py: the engine's curves as integers */", "#pragma once",
           "#include <stdint.h>", ""]
    # phase increment of MIDI note n: f * 2^32 / FS
    inc = [min(0xFFFFFFFF, round(440 * 2 ** ((n - 69) / 12) * 2 ** 32 / FS)) for n in range(128)]
    out.append(arr("uint32_t", "PITCH_INC", inc, 6))
    # semitone fractions for glide / fine tune: 2^(k/256 semitone) in Q16, k = 0..255
    out.append(arr("uint16_t", "SEMI_FRAC", [round(2 ** (k / 256 / 12) * 32768) for k in range(256)]))
    # TPT SVF g = tan(pi fc / fs) in Q14, cutoff index 0..255 exponential 30 Hz .. 16 kHz
    lo, hi = 30.0, 16000.0
    g = [round(math.tan(math.pi * lo * (hi / lo) ** (i / 255) / FS) * 16384) for i in range(256)]
    out.append(arr("int32_t", "SVF_G", g, 10))
    # exponential decay per control tick, Q16: param 0..127 -> time to -60 dB from 4 ms to 12 s
    def t60(p, a=0.004, b=12.0):
        return a * (b / a) ** (p / 127)
    dec = [min(65535, round(math.exp(-6.9078 * CR / (t60(p) * FS)) * 65536)) for p in range(128)]
    out.append(arr("uint32_t", "DECAY_Q16", dec, 10))
    # linear attack: Q24 per control tick, param 0..127 -> 1 ms .. 4 s
    att = [max(1, round((1 << 24) * CR / (0.001 * (4000 ** (p / 127)) * FS))) for p in range(128)]
    out.append(arr("uint32_t", "ATTACK_Q24", att, 8))
    # one-pole smoothing for slews: coefficient Q15 for time constants 0.5 ms .. 500 ms per sample
    sm = [round((1 - math.exp(-1 / (0.0005 * (1000 ** (p / 127)) * FS))) * 32768) for p in range(128)]
    out.append(arr("int32_t", "ONEPOLE_Q15", sm, 12))
    # supersaw detune curve (JP-8000 measurements, after Szabo): amount 0..127 -> Q15
    det = []
    for p in range(128):
        x = p / 127
        y = (10028.7312891634 * x ** 11 - 50818.8652045924 * x ** 10 + 111363.4808729368 * x ** 9
             - 138150.6761080548 * x ** 8 + 106649.6679158292 * x ** 7 - 53046.9642751875 * x ** 6
             + 17019.9518580080 * x ** 5 - 3425.0836591318 * x ** 4 + 404.2703938388 * x ** 3
             - 24.1878824391 * x ** 2 + 0.6717417634 * x + 0.0030115596)
        det.append(max(0, round(y * 32768)))
    out.append(arr("int32_t", "DETUNE_Q15", det, 12))
    (GEN / "apex_tables.h").write_text("\n".join(out))

